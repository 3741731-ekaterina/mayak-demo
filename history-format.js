export function readableHistory(k,v,{kind='',resolve=()=>null}={}){
 if(v==null||v==='')return 'Не указано';if(typeof v==='boolean')return v?'Да':'Нет';
 if(Array.isArray(v))return v.length?v.map(x=>readableHistory(k,x,{kind,resolve})).join('; '):'Нет';
 if(typeof v==='object')return Object.entries(v).filter(([key])=>historyFieldVisible(key)).map(([key,value])=>historyField(key,kind)+': '+readableHistory(key,value,{kind,resolve})).join('; ')||'Нет';
 if(references[k])return resolve(references[k],String(v))||'Прежняя запись справочника';
 if(k==='field')return historyField(v,kind);if(k==='payrollMode'&&v==='pending')return 'Расчёт не согласован';
 if(k==='permissions')return permissions[v]||'Дополнительное разрешение';
 if(['timeRoute','pieceRoute','adjustmentRoute'].includes(k))return resolve('users',String(v))||values[v]||'Прежний участник согласования';
 if(/^\d{4}-\d{2}-\d{2}$/.test(String(v)))return String(v).split('-').reverse().join('.');
 if(/^\d{4}-\d{2}-\d{2}T/.test(String(v))&&!Number.isNaN(Date.parse(v)))return new Date(v).toLocaleString('ru-RU',{timeZone:'Europe/Moscow'});
 if(k==='status'&&v==='active')return kind==='employees'?'Работает':'Активен';
 return values[v]||String(v);
}
